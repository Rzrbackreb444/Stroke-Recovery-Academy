import { useQuery } from "@tanstack/react-query";
import { useEffect, useMemo, useState } from "react";
import { Card } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Link } from "wouter";
import {
  Music,
  MessageCircle,
  Flame,
  Brain,
  Pencil,
  Sun,
  Sparkles,
  Star,
  Compass,
  X,
  Quote,
} from "lucide-react";

type RecommendationItem = {
  id: string;
  quote: string;
  body: string;
  ctaLabel: string;
  ctaHref: string;
  icon: string;
};

const ICONS: Record<string, React.ComponentType<{ className?: string }>> = {
  music: Music,
  messageCircle: MessageCircle,
  flame: Flame,
  brain: Brain,
  pencil: Pencil,
  sun: Sun,
  sparkles: Sparkles,
  star: Star,
  compass: Compass,
};

const DISMISS_KEY_PREFIX = "rec-dismiss:";
const DISMISS_MS = 7 * 24 * 60 * 60 * 1000; // 7 days

function isDismissed(id: string): boolean {
  try {
    const ts = Number(localStorage.getItem(DISMISS_KEY_PREFIX + id) ?? 0);
    return ts > 0 && Date.now() - ts < DISMISS_MS;
  } catch {
    return false;
  }
}

function dismiss(id: string) {
  try {
    localStorage.setItem(DISMISS_KEY_PREFIX + id, String(Date.now()));
  } catch {
    /* ignore */
  }
}

/**
 * Inline recommendation cards. Never modal, never blocking. Each card is
 * dismissible for 7 days via localStorage. Copy is generated by Gemini per
 * surface per user per day; static fallbacks render when the LLM is down.
 */
export function RecommendationCards({ surface }: { surface: string }) {
  const { data, isLoading } = useQuery<{ items: RecommendationItem[] }>({
    queryKey: ["/api/recovery/recommendations", surface],
    queryFn: async () => {
      const r = await fetch(
        `/api/recovery/recommendations?surface=${encodeURIComponent(surface)}`,
        { credentials: "include" },
      );
      if (!r.ok) return { items: [] };
      return r.json();
    },
    staleTime: 5 * 60 * 1000,
  });

  const [dismissedTick, setDismissedTick] = useState(0);
  const visible = useMemo(() => {
    return (data?.items ?? []).filter((it) => !isDismissed(it.id));
  }, [data, dismissedTick]);

  if (isLoading || visible.length === 0) return null;

  return (
    <div className="space-y-3" data-testid={`recs-${surface}`}>
      {visible.map((rec) => {
        const Icon = ICONS[rec.icon] ?? Sparkles;
        return (
          <Card
            key={rec.id}
            className="p-5 bg-gradient-to-br from-amber-900/15 to-stone-900 border-amber-700/30 relative"
            data-testid={`rec-card-${rec.id}`}
          >
            <Button
              size="icon"
              variant="ghost"
              className="absolute top-2 right-2 w-7 h-7 text-stone-500 hover:text-stone-300"
              onClick={() => {
                dismiss(rec.id);
                setDismissedTick((n) => n + 1);
              }}
              aria-label="Dismiss recommendation"
              data-testid={`button-dismiss-${rec.id}`}
            >
              <X className="w-4 h-4" />
            </Button>
            <div className="flex gap-3 pr-6">
              <div className="flex-shrink-0 w-10 h-10 rounded-md bg-amber-900/40 flex items-center justify-center">
                <Icon className="w-5 h-5 text-amber-400" />
              </div>
              <div className="flex-1">
                <div
                  className="text-amber-300 font-bold text-base mb-1 leading-snug"
                  data-testid={`rec-quote-${rec.id}`}
                >
                  <Quote className="w-3 h-3 inline -mt-1 mr-1 text-amber-500/70" />
                  {rec.quote}
                </div>
                <p
                  className="text-stone-300 text-sm mb-3 leading-relaxed"
                  data-testid={`rec-body-${rec.id}`}
                >
                  {rec.body}
                </p>
                <Link href={rec.ctaHref}>
                  <Button
                    size="sm"
                    className="bg-amber-600 hover:bg-amber-700 text-white"
                    data-testid={`rec-cta-${rec.id}`}
                  >
                    {rec.ctaLabel}
                  </Button>
                </Link>
              </div>
            </div>
          </Card>
        );
      })}
    </div>
  );
}

// Re-export for convenience.
export default RecommendationCards;
